def _wait_until(service, project_id, timeout=30.0):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if not service.is_indexing(project_id):
            return service.index_health(project_id)
        time.sleep(0.05)
    return service.index_health(project_id)


