class ProvenanceTests(unittest.TestCase):
    def test_fingerprint_components_carry_provenance(self):
        from pathlib import Path
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "a.py").write_text("x = 1\n")
            db_path = str(root / "main.db")
            engineering = EngineeringService(lambda: backend._connect(db_path))
            project = engineering.register_project("prov", str(root))
            service = IntelligenceService(
                engineering.projects,
                str(root / "intel"),
            )
            fingerprint = service.fingerprint_for(project.project_id)
            self.assertTrue(fingerprint.components)
            self.assertTrue(all(c.provenance.kind for c in fingerprint.components))
            self.assertEqual(fingerprint.schema_version, 1)


